CREATE EXTENSION IF NOT EXISTS ltree;

CREATE TYPE target_group AS ENUM ('women', 'men', 'kids_girls', 'kids_boys', 'unisex');
CREATE TYPE publication_status AS ENUM ('draft', 'active', 'archived');
CREATE TYPE color_family AS ENUM (
  'black', 'white', 'grey', 'blue', 'navy', 'red', 'pink', 'green',
  'khaki', 'beige', 'brown', 'yellow', 'orange', 'purple', 'multicolour'
);
CREATE TYPE size_system AS ENUM ('alpha', 'eu_shoe', 'jeans', 'kids_height', 'one_size');
CREATE TYPE size_availability AS ENUM ('in_stock', 'low_stock', 'out_of_stock');
CREATE TYPE image_kind AS ENUM ('packshot', 'model', 'detail');

-- Identities are BY DEFAULT so the seed import can load explicit ids; it resets the
-- sequences afterwards.
CREATE TABLE brands (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE,
  name text NOT NULL,
  is_premium boolean NOT NULL DEFAULT false
);

CREATE TABLE categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE,
  name text NOT NULL,
  parent_id bigint REFERENCES categories (id),
  path ltree NOT NULL UNIQUE,
  depth integer GENERATED ALWAYS AS (nlevel(path)) STORED,
  is_leaf boolean NOT NULL
);

CREATE INDEX categories_path ON categories USING gist (path);

CREATE TABLE size_charts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  system size_system NOT NULL,
  sizes text[] NOT NULL CHECK (cardinality(sizes) > 0)
);

CREATE TABLE products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  model_sku text NOT NULL UNIQUE,
  brand_id bigint NOT NULL REFERENCES brands (id),
  category_id bigint NOT NULL REFERENCES categories (id),
  target_group target_group NOT NULL,
  name text NOT NULL,
  description text NOT NULL DEFAULT '',
  attributes jsonb NOT NULL DEFAULT '{}',
  sustainability text[] NOT NULL DEFAULT '{}',
  size_chart_id bigint REFERENCES size_charts (id),
  status publication_status NOT NULL DEFAULT 'draft',
  -- Aggregate version: bumped by every write to the product, its articles or sizes.
  -- It is the ETag of the product view and the value If-Match is checked against.
  version integer NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);

CREATE TABLE articles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES products (id),
  article_sku text NOT NULL UNIQUE,
  color_name text NOT NULL,
  color_family color_family NOT NULL,
  price_cents integer NOT NULL CHECK (price_cents > 0),
  original_price_cents integer CHECK (original_price_cents > price_cents),
  currency char(3) NOT NULL DEFAULT 'EUR' CHECK (currency = 'EUR'),
  discount_pct smallint GENERATED ALWAYS AS (
    CASE
      WHEN original_price_cents IS NULL THEN 0
      ELSE round(100.0 * (original_price_cents - price_cents) / original_price_cents)
    END
  ) STORED,
  is_on_sale boolean GENERATED ALWAYS AS (original_price_cents IS NOT NULL) STORED,
  popularity_score integer NOT NULL DEFAULT 0,
  released_at timestamptz NOT NULL DEFAULT now(),
  status publication_status NOT NULL DEFAULT 'active',
  in_stock boolean NOT NULL DEFAULT false,
  -- Copied from the product in the same transaction as every product write, so that
  -- listing filters and sorts are served by one index on this table without joins
  -- (docs/adr/0003-product-article-size-model.md).
  brand_id bigint NOT NULL REFERENCES brands (id),
  category_id bigint NOT NULL REFERENCES categories (id),
  target_group target_group NOT NULL,
  product_status publication_status NOT NULL,
  deleted_at timestamptz
);

-- Every listing index is partial on the same "listed" predicate, which listing queries
-- repeat verbatim so the planner can match it. Descending sorts include id DESC so the
-- keyset comparison (sort_key, id) < ($1, $2) stays a single index range.
CREATE INDEX articles_category_popular ON articles (category_id, popularity_score DESC, id DESC)
  WHERE deleted_at IS NULL AND status = 'active' AND product_status = 'active';
CREATE INDEX articles_category_price ON articles (category_id, price_cents, id)
  WHERE deleted_at IS NULL AND status = 'active' AND product_status = 'active';
CREATE INDEX articles_category_newest ON articles (category_id, released_at DESC, id DESC)
  WHERE deleted_at IS NULL AND status = 'active' AND product_status = 'active';
CREATE INDEX articles_popular ON articles (popularity_score DESC, id DESC)
  WHERE deleted_at IS NULL AND status = 'active' AND product_status = 'active';
CREATE INDEX articles_price ON articles (price_cents, id)
  WHERE deleted_at IS NULL AND status = 'active' AND product_status = 'active';
CREATE INDEX articles_newest ON articles (released_at DESC, id DESC)
  WHERE deleted_at IS NULL AND status = 'active' AND product_status = 'active';
CREATE INDEX articles_discount ON articles (discount_pct DESC, id DESC)
  WHERE deleted_at IS NULL AND status = 'active' AND product_status = 'active' AND is_on_sale;
CREATE INDEX articles_brand_category ON articles (brand_id, category_id)
  WHERE deleted_at IS NULL AND status = 'active' AND product_status = 'active';
CREATE INDEX articles_product ON articles (product_id);

CREATE TABLE article_sizes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  article_id bigint NOT NULL REFERENCES articles (id),
  size_label text NOT NULL,
  size_sort smallint NOT NULL,
  gtin char(13) NOT NULL UNIQUE,
  availability size_availability NOT NULL DEFAULT 'in_stock',
  -- Also serves lookups of all sizes of an article, so no separate (article_id) index.
  UNIQUE (article_id, size_label)
);

CREATE INDEX article_sizes_available ON article_sizes (size_label, article_id)
  WHERE availability <> 'out_of_stock';

CREATE TABLE article_images (
  article_id bigint NOT NULL REFERENCES articles (id),
  position smallint NOT NULL,
  kind image_kind NOT NULL,
  url text NOT NULL,
  width integer NOT NULL,
  height integer NOT NULL,
  PRIMARY KEY (article_id, position)
);

CREATE TABLE idempotency_keys (
  key text PRIMARY KEY,
  request_hash text NOT NULL,
  response_status integer NOT NULL,
  response_body jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
